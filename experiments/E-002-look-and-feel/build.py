#!/usr/bin/env python3
"""Assemble the three self-contained pages from src/. Run: python3 build.py"""
from pathlib import Path
here = Path(__file__).parent
src = here / "src"
names = {"slack-like": "Slack-like", "telegram-like": "Telegram-like", "own": "The agent's own"}
theme = (src / "theme.js").read_text()
for slug, title in names.items():
    css = (src / "core.css").read_text() + "\n" + (src / f"{slug}.css").read_text()
    js = (src / f"{slug}.js").read_text() + "\n" + (src / "core.js").read_text()
    html = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#ffffff">
<script>
{theme}</script>
<title>E-002 feed, {title}</title>
<!-- Generated by build.py from src/. Edit the sources, not this file. A mock-up: nothing here is product code. -->
<style>
{css}</style>
</head>
<body>
<div id="app"></div>
<script>
{js}</script>
</body>
</html>
"""
    (here / f"{slug}.html").write_text(html)
    print(f"built {slug}.html ({len(html) // 1024} KB)")
import re
for page in ["control-panel.html", "notification-app.html"]:  # the two outside pages share the theme
    t = (here / page).read_text()
    t = re.sub(r"<!--theme-->.*?<!--/theme-->", lambda m: "<!--theme--><meta name=\"theme-color\" content=\"#ffffff\"><script>\n" + theme + "</script><!--/theme-->", t, flags=re.S)
    (here / page).write_text(t)
